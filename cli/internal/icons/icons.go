// Package icons reads registry/icons/icons.json, the map from Velyx icon names
// to each supported icon set, and renders the icon Blade component from it.
package icons

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

// Map is the content of icons.json.
type Map struct {
	Default   string                       `json:"default"`
	Libraries map[string]Library           `json:"libraries"`
	Icons     map[string]map[string]string `json:"icons"`
}

// Library describes one icon set and how its Blade components are named.
type Library struct {
	Label     string `json:"label"`
	Composer  string `json:"composer"`
	Component string `json:"component"`
}

// Load reads and validates icons.json.
func Load(path string) (*Map, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	return Parse(data)
}

// Parse decodes and validates icons.json content.
func Parse(data []byte) (*Map, error) {
	var m Map
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, fmt.Errorf("decode icons.json: %w", err)
	}

	return &m, m.Validate()
}

// Validate checks that the default set exists and every icon names every set.
func (m *Map) Validate() error {
	if _, ok := m.Libraries[m.Default]; !ok {
		return fmt.Errorf("icons: default set %q is not defined", m.Default)
	}
	for name, lib := range m.Libraries {
		if !strings.Contains(lib.Component, "{name}") {
			return fmt.Errorf("icons: set %q component pattern must contain {name}", name)
		}
	}
	for icon, perSet := range m.Icons {
		for set := range m.Libraries {
			if perSet[set] == "" {
				return fmt.Errorf("icons: %q has no name for set %q", icon, set)
			}
		}
	}

	return nil
}

// Has reports whether a Velyx icon name is mapped.
func (m *Map) Has(name string) bool {
	_, ok := m.Icons[name]
	return ok
}

// Sets returns the icon set keys in a stable order.
func (m *Map) Sets() []string {
	sets := make([]string, 0, len(m.Libraries))
	for k := range m.Libraries {
		sets = append(sets, k)
	}
	sort.Strings(sets)

	return sets
}

// Component returns the Blade component name for an icon in a set.
func (m *Map) Component(icon, set string) string {
	return strings.ReplaceAll(m.Libraries[set].Component, "{name}", m.Icons[icon][set])
}

// Blade renders resources/views/components/ui/icon.blade.php. The chosen set is
// a plain prop default so the CLI can switch sets with a one-line edit.
func (m *Map) Blade(set string) (string, error) {
	if _, ok := m.Libraries[set]; !ok {
		return "", fmt.Errorf("icons: unknown set %q", set)
	}

	names := make([]string, 0, len(m.Icons))
	for k := range m.Icons {
		names = append(names, k)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("{{-- Generated by Velyx from registry/icons/icons.json. Switch sets with `velyx icons use <set>`. --}}\n")
	b.WriteString("@props([\n    'name',\n")
	fmt.Fprintf(&b, "    'set' => '%s',\n", set)
	b.WriteString("])\n\n@php\n    $icons = [\n")
	for _, icon := range names {
		fmt.Fprintf(&b, "        '%s' => [", icon)
		for i, s := range m.Sets() {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "'%s' => '%s'", s, m.Component(icon, s))
		}
		b.WriteString("],\n")
	}
	b.WriteString("    ];\n\n    // Names that are not in the map are passed to the set as-is, so any icon of the set works.\n    $patterns = [")
	for i, s := range m.Sets() {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "'%s' => '%s'", s, m.Libraries[s].Component)
	}
	b.WriteString("];\n\n")
	b.WriteString("    $component = $icons[$name][$set] ?? str_replace('{name}', $name, $patterns[$set] ?? '{name}');\n")
	b.WriteString("    $a11y = $attributes->has('aria-label') ? ['role' => 'img'] : ['aria-hidden' => 'true'];\n")
	b.WriteString("@endphp\n\n")
	b.WriteString("<x-dynamic-component :component=\"$component\" {{ $attributes->merge($a11y)->class('shrink-0') }} />\n")

	return b.String(), nil
}
