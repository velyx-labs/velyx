package tokens

import (
	"fmt"
	"go/format"
	"strings"
)

// GoPalette renders a Go source file exposing every color token as a
// light/dark pair, so the CLI's terminal UI uses the same palette as the web.
func (f *File) GoPalette(pkg string) ([]byte, error) {
	first := f.firstTheme()
	dark, hasDark := f.darkTheme()
	if !hasDark {
		dark = first
	}

	var b strings.Builder
	b.WriteString("// Code generated by velyx-tokens from tokens/tokens.json. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("// Color is a design token resolved for a light and a dark terminal background.\n")
	b.WriteString("type Color struct {\n\tLight string\n\tDark  string\n}\n\n")
	b.WriteString("// Palette colors, in tokens.json order.\nvar (\n")

	for _, token := range f.Color.Tokens {
		light, err := f.resolveColor(token.Name, first, 0)
		if err != nil {
			return nil, err
		}
		darkValue, err := f.resolveColor(token.Name, dark, 0)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t// %s\n\t%s = Color{Light: %q, Dark: %q}\n", oneLine(token.Usage), identifier(token.Name), light, darkValue)
	}
	b.WriteString(")\n")

	return format.Source([]byte(b.String()))
}

// identifier turns a token name such as "surface-raised" into "SurfaceRaised".
func identifier(name string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' || r == '.' }) {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}

	return b.String()
}

func oneLine(text string) string {
	return strings.Join(strings.Fields(text), " ")
}
