package tokens

import (
	"fmt"
	"sort"
	"strings"
)

const cssPrefix = "velyx"

// CSS renders a Tailwind v4 stylesheet: raw custom properties per theme, then
// an @theme inline block that maps them to Tailwind's color, radius, font,
// shadow and text utilities.
func (f *File) CSS() string {
	var b strings.Builder
	first := f.firstTheme()

	b.WriteString("/* Generated by velyx-tokens from tokens/tokens.json. Do not edit. */\n\n")

	b.WriteString(":root {\n")
	for _, token := range f.Color.Tokens {
		writeVar(&b, token.Name, cssValue(token.Value.In(first, first)))
	}
	for _, token := range f.Shadow.Tokens {
		writeVar(&b, token.Name, token.Value.In(first, first))
	}
	for _, token := range f.Spacing.Tokens {
		writeVar(&b, token.Name, token.Value)
	}
	for _, token := range f.Radius.Tokens {
		writeVar(&b, token.Name, token.Value)
	}
	for _, key := range sortedKeys(f.Type.Families) {
		writeVar(&b, "font-"+key, f.Type.Families[key])
	}
	b.WriteString("}\n")

	if dark, ok := f.darkTheme(); ok && dark != first {
		overrides := f.themeOverrides(dark)
		b.WriteString("\n@media (prefers-color-scheme: dark) {\n  :root:not(.light):not([data-theme=\"light\"]) {\n")
		b.WriteString(indent(overrides, "  "))
		b.WriteString("  }\n}\n\n")
		b.WriteString(".dark,\n[data-theme=\"dark\"] {\n")
		b.WriteString(overrides)
		b.WriteString("}\n")
	}

	b.WriteString("\n@theme inline {\n")
	for _, token := range f.Color.Tokens {
		fmt.Fprintf(&b, "  --color-%s: var(--%s-%s);\n", token.Name, cssPrefix, token.Name)
	}
	for _, token := range f.Radius.Tokens {
		fmt.Fprintf(&b, "  --%s: var(--%s-%s);\n", token.Name, cssPrefix, token.Name)
	}
	for _, token := range f.Shadow.Tokens {
		fmt.Fprintf(&b, "  --%s: var(--%s-%s);\n", token.Name, cssPrefix, token.Name)
	}
	for _, key := range sortedKeys(f.Type.Families) {
		fmt.Fprintf(&b, "  --font-%s: var(--%s-font-%s);\n", key, cssPrefix, key)
	}
	for _, group := range f.Type.Groups {
		for _, style := range group.Styles {
			fmt.Fprintf(&b, "  --text-%s: %s;\n", style.Name, style.FontSize)
			if style.LineHeight != "" {
				fmt.Fprintf(&b, "  --text-%s--line-height: %s;\n", style.Name, style.LineHeight)
			}
			if style.LetterSpacing != "" {
				fmt.Fprintf(&b, "  --text-%s--letter-spacing: %s;\n", style.Name, style.LetterSpacing)
			}
			if style.FontWeight != 0 {
				fmt.Fprintf(&b, "  --text-%s--font-weight: %d;\n", style.Name, style.FontWeight)
			}
		}
	}
	b.WriteString("}\n")

	return b.String()
}

// themeOverrides lists only the color and shadow tokens whose value differs from the first theme.
func (f *File) themeOverrides(themeID string) string {
	var b strings.Builder
	first := f.firstTheme()
	for _, token := range f.Color.Tokens {
		if value := token.Value.In(themeID, first); value != token.Value.In(first, first) {
			writeVar(&b, token.Name, cssValue(value))
		}
	}
	for _, token := range f.Shadow.Tokens {
		if value := token.Value.In(themeID, first); value != token.Value.In(first, first) {
			writeVar(&b, token.Name, value)
		}
	}

	return b.String()
}

func writeVar(b *strings.Builder, name, value string) {
	fmt.Fprintf(b, "  --%s-%s: %s;\n", cssPrefix, name, value)
}

// cssValue turns a {token} alias into a var() reference and leaves literals alone.
func cssValue(value string) string {
	if match := aliasPattern.FindStringSubmatch(value); match != nil {
		return fmt.Sprintf("var(--%s-%s)", cssPrefix, match[1])
	}

	return value
}

func indent(text, prefix string) string {
	lines := strings.SplitAfter(text, "\n")
	for i, line := range lines {
		if line != "" {
			lines[i] = prefix + line
		}
	}

	return strings.Join(lines, "")
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	return keys
}
